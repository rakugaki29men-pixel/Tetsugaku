def compute_similar(all_people, threshold=25.0, top_n=3):
    """
    4軸スコア（0〜100）のユークリッド距離が近い順にtop_n人を返す。
    ただし距離が threshold を超える相手は候補に入れない
    （＝誰とも近くない場合はリストが空になる）。
    戻り値: {id: [{id, note}, ...]}
    """
    import math

    axis_keys = ["ti", "up", "re", "sd"]
    result = {}
    for a in all_people:
        dists = []
        for b in all_people:
            if b["id"] == a["id"]:
                continue
            d = math.sqrt(sum((a["pos"][k] - b["pos"][k]) ** 2 for k in axis_keys))
            dists.append((d, b))
        dists.sort(key=lambda x: x[0])
        near = [b for d, b in dists if d <= threshold][:top_n]
        result[a["id"]] = [{"id": b["id"], "note": "思想が近い"} for b in near]
    return result


