def resolve_chouonpu(kana):
    """
    「ー」（長音記号）を直前の母音に変換する。端末・ブラウザによって「ー」の
    ソート順の扱いが揺れることがあるため、あらかじめ純粋なひらがなだけの
    文字列にしておき、単純な文字コード比較でも常に正しい50音順になるようにする。
    """
    out = []
    for ch in kana:
        if ch == "ー" and out:
            out.append(_HIRAGANA_VOWEL_OF.get(out[-1], out[-1]))
        else:
            out.append(ch)
    return "".join(out)


def extract_keywords(thought, ism):
    """
    「思想」欄（・区切り）と「主義・学派」欄から、チャット内で光らせる
    キーワード候補を抽出する。長すぎる文章的なフレーズは除外する。
    """
    keywords = []
    for raw in (thought or "").split("・"):
        term = raw.strip().strip("「」")
        # 「万物は流転する」のような文っぽい語尾は候補として少し長めでも許容するが、
        # 極端に長い説明文はチャット内ハイライトに向かないので除外する。
        if term and len(term) <= 14 and term not in keywords:
            keywords.append(term)
    for raw in (ism or "").split("・"):
        term = raw.strip()
        term = term.split("（")[0].strip()  # 「汎神論・合理主義」の括弧注記等を軽く整理
        if term and term not in keywords:
            keywords.append(term)
    return keywords


